/*
 * Writes the stroke test fixtures (CLAUDE.md §7.5, §9) from KanjiVG (vendor-src/kanjivg-main.zip):
 *   tests/fixtures/traces/<hex>.json   20 kana + 20 kanji: medians and labelled synthetic traces
 *                                      (core lib/strokes/synth.ts; not recorded by hand)
 *   tests/fixtures/kanjivg/<hex>.svg   the source SVGs, so the extractor and the stroke-order spot
 *                                      checks (必 右 左 生) run without the zip. CC BY-SA 3.0, KanjiVG.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { synthSamples } from '@ladder/core/lib/strokes/synth';
import { kvgToStrokes } from '@/lib/ja/kvg';

export const FIXTURE_KANA = [...'あいうおきさしすなぬのはゆをアカシツソン'];
export const FIXTURE_KANJI = [...'一二三人口大日月山川上下中本生右左必田学'];

const ROOT = process.cwd();
const ZIP = path.join(ROOT, 'vendor-src', 'kanjivg-main.zip');
const TRACES = path.join(ROOT, 'tests', 'fixtures', 'traces');
const SVGS = path.join(ROOT, 'tests', 'fixtures', 'kanjivg');

fs.mkdirSync(TRACES, { recursive: true });
fs.mkdirSync(SVGS, { recursive: true });
let n = 0;
for (const [ci, ch] of [...FIXTURE_KANA, ...FIXTURE_KANJI].entries()) {
  const hex = ch.codePointAt(0)!.toString(16).padStart(5, '0');
  const svg = execFileSync('unzip', ['-p', ZIP, `kanji/${hex}.svg`], { encoding: 'utf8' });
  fs.writeFileSync(path.join(SVGS, `${hex}.svg`), svg);
  const { medians } = kvgToStrokes(svg);
  const samples = synthSamples(medians, 2000 + ci);
  fs.writeFileSync(path.join(TRACES, `${ch.codePointAt(0)!.toString(16)}.json`), `${JSON.stringify({ char: ch, medians, samples })}\n`);
  n += samples.length;
}
fs.writeFileSync(
  path.join(TRACES, 'README.md'),
  '# Trace fixtures\n\nLabelled sample traces for the stroke matcher (core `lib/strokes/trace.ts`), one file per character\n' +
    '(named by code point): 20 kana and 20 kanji. Generated by `npx tsx scripts/make-trace-fixtures.ts` from KanjiVG\n' +
    'medians with seeded jitter, **not recorded by hand**. Add traces recorded on phones and tablets (as `samples`\n' +
    'with the same shape) before tuning the thresholds further.\n',
);
console.log(`trace fixtures — ${FIXTURE_KANA.length} kana, ${FIXTURE_KANJI.length} kanji, ${n} samples`);
